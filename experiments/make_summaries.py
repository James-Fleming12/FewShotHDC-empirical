"""Regenerate ``results/summary.md`` from the experiment CSVs.

Run after ``experiments/run_all.py`` (quick or --full).
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd
from scipy import stats

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"


def _paired(df, index_cols, pairs, value="acc", columns="config"):
    """Paired t-tests over seeds for aligned (setting, seed) cells."""
    wide = df.pivot_table(index=list(index_cols) + ["seed"], columns=columns,
                          values=value, aggfunc="mean")
    rows = []
    for a, b in pairs:
        if a not in wide.columns or b not in wide.columns:
            continue
        sub = wide[[a, b]].dropna()
        if len(sub) < 2:
            continue
        diff = sub[a] - sub[b]
        _, p = stats.ttest_rel(sub[a], sub[b])
        rows.append({"comparison": f"{a} - {b}", "n": len(sub),
                     "mean_diff": diff.mean(), "std": diff.std(ddof=1), "p": p})
    return pd.DataFrame(rows).round(4) if rows else None


def _load(name: str) -> pd.DataFrame | None:
    path = RESULTS / f"{name}.csv"
    return pd.read_csv(path) if path.exists() else None


def _block(title: str, df: pd.DataFrame) -> str:
    return f"### {title}\n\n```\n{df.to_string()}\n```\n"


def _pivot(df, index, columns="config", value="acc"):
    return df.pivot_table(index=index, columns=columns, values=value, aggfunc="mean").round(3)


def _agg(df, index, value="acc"):
    return df.groupby(index)[value].mean().round(3)


def main() -> None:
    parts = ["# FewShotHDC: generated result summary\n",
             "Regenerated by `python experiments/make_summaries.py` from the "
             "CSV files in `results/`.\n"]

    # ---------------------------------------------------------------- exp1
    df = _load("exp1_fewshot")
    if df is not None:
        parts.append("\n## Exp 1: few-shot ability\n")
        parts.append(_block("Test accuracy by SNR / shots / config",
                            _pivot(df, ["snr", "shots"])))
        parts.append(_block("Encode budget (equivalent samples, mean over seeds)",
                            _pivot(df, ["snr", "shots"], value="n_encoded")))
    df = _load("exp1_fewshot_enc")
    if df is not None:
        parts.append(_block("Encoder comparison (accuracy)",
                            _pivot(df, ["encoder", "snr", "shots"])))

    # ---------------------------------------------------------------- exp2
    parts.append("\n## Exp 2: breakage scenarios\n")
    for name in ("overlap", "label_noise", "capacity", "imbalance", "noise_dims"):
        df = _load(f"exp2_{name}")
        if df is None:
            continue
        index = {"overlap": "snr", "label_noise": "label_noise", "capacity": "capacity_dim",
                 "imbalance": "imbalance_ratio", "noise_dims": "n_noise_dims"}[name]
        parts.append(_block(f"{name}: accuracy", _pivot(df, index)))
        if name == "imbalance":
            parts.append(_block("imbalance: rarest-class recall",
                                _pivot(df, index, value="min_class_recall")))
        t = _paired(df, [index], [("full", "full_init"), ("buffer", "full"),
                                  ("fewshot", "full")])
        if t is not None:
            parts.append(_block(f"{name}: paired tests (accuracy)", t))
    df = _load("exp2_contamination")
    if df is not None:
        fs = df[df.config == "fewshot"]
        parts.append(_block("contamination (few-shot): accuracy",
                            _agg(fs, ["contam_mode", "contam_frac"])))

    # ---------------------------------------------------------------- exp3
    df = _load("exp3_prototypes")
    if df is not None:
        parts.append("\n## Exp 3: prototype sample complexity\n")
        for value in ("cos_oracle_mean", "margin_mean", "acc"):
            parts.append(_block(f"{value} (shots x SNR)",
                                _pivot(df, "shots", columns="snr", value=value)))
    df = _load("exp3_shots_to_target")
    if df is not None:
        parts.append(_block("shots to target accuracy",
                            df.pivot_table(index=["sweep_kind", "sweep_value"],
                                           columns="target",
                                           values="shots_to_target").round(2)))

    # ---------------------------------------------------------------- exp4
    parts.append("\n## Exp 4: robustness\n")
    df = _load("exp4_feature_noise")
    if df is not None:
        parts.append(_block("feature noise: accuracy", _pivot(df, "test_noise")))
        parts.append(_block("feature noise: macro recall",
                            _pivot(df, "test_noise", value="macro_recall")))
        t = _paired(df, ["test_noise"], [("fewshot", "full"), ("buffer", "full")])
        if t is not None:
            parts.append(_block("feature noise: paired tests (accuracy)", t))
    df = _load("exp4_domain_shift")
    if df is not None:
        parts.append(_block("domain shift: accuracy", _pivot(df, ["shift_kind", "shift_severity"])))
        t = _paired(df, ["shift_kind", "shift_severity"],
                    [("fewshot", "full"), ("buffer", "full")])
        if t is not None:
            parts.append(_block("domain shift: paired tests (accuracy)", t))
    df = _load("exp4_support_shift")
    if df is not None:
        fs = df[df.config == "fewshot"]
        ref = df[df.config.isin(["full", "buffer", "full_init"])]
        parts.append(_block("support shift: few-shot accuracy",
                            _pivot(fs, ["shift_kind", "shift_severity"], columns="support_domain")))
        parts.append(_block("support shift: source-trained references",
                            _pivot(ref, ["shift_kind", "shift_severity"])))
    df = _load("exp4_prior_shift")
    if df is not None:
        parts.append(_block("prior shift: accuracy", _pivot(df, "prior_skew")))
        parts.append(_block("prior shift: macro recall",
                            _pivot(df, "prior_skew", value="macro_recall")))
        t = _paired(df, ["prior_skew"], [("fewshot", "full"), ("buffer", "full")])
        if t is not None:
            parts.append(_block("prior shift: paired tests (accuracy)", t))
    df = _load("exp4_imbalance")
    if df is not None:
        parts.append(_block("imbalance policies: accuracy", _pivot(df, "imbalance_ratio", columns="policy")))
        parts.append(_block("imbalance policies: rarest-class recall",
                            _pivot(df, "imbalance_ratio", columns="policy",
                                   value="min_class_recall")))
        t = _paired(df, ["imbalance_ratio"],
                    [("fewshot_balanced", "fewshot_natural"),
                     ("fewshot_balanced", "full")], columns="policy")
        if t is not None:
            parts.append(_block("imbalance policies: paired tests (accuracy)", t))

    out = RESULTS / "summary.md"
    out.write_text("\n".join(parts))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
